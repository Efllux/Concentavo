import assert from 'node:assert/strict';
import {separateVoiceNotes,inferredVoiceCount} from '../src/voice-separation.js';
const note=(start,midi,extra={})=>({start,midi,duration:1,sourceVoice:'1',...extra});
const notes=[note(0,72),note(0,60),note(1,74),note(1,62),note(2,76),note(2,64)];
assert.equal(inferredVoiceCount(notes),2);
assert.equal(inferredVoiceCount([note(0,72),note(0,60),note(1,74)]),1,'A single chord is not sufficient automatic evidence');
assert.deepEqual(separateVoiceNotes(notes,2).voices.map(v=>v.map(n=>n.midi)),[[72,74,76],[60,62,64]]);
const crossed=[note(0,65,{sourceVoice:'1',stem:'up'}),note(0,60,{sourceVoice:'2',stem:'down'}),note(1,59,{sourceVoice:'1',stem:'up'}),note(1,64,{sourceVoice:'2',stem:'down'})];
assert.deepEqual(separateVoiceNotes(crossed,2).voices.map(v=>v.map(n=>n.midi)),[[65,59],[60,64]],'Written labels and stems keep crossing voices intact');
const held=[note(0,72,{duration:2,tieStart:true}),note(0,60),note(1,62),note(2,72,{tieStop:true}),note(2,64)];
const sustained=separateVoiceNotes(held,2);
assert.deepEqual(sustained.voices.map(v=>v.map(n=>n.midi)),[[72,72],[60,62,64]],'A moving lower voice does not steal a held or tied upper note');
assert.equal(sustained.crowded,false);
const unison=[...notes,note(3,67)];
assert.ok(separateVoiceNotes(unison,2).voices.every(v=>v.at(-1).midi===67),'Single written notes can be shared');
assert.equal(separateVoiceNotes(unison,2,{unisons:false}).voices.flat().length,unison.length,'Solo mode assigns each note once');
const pickup=[...notes,note(3,72,{sourceVoice:'2',stem:'up'}),note(4,72,{sourceVoice:'1',stem:'up'}),note(4,60,{sourceVoice:'2',stem:'down'})];
const pickupSplit=separateVoiceNotes(pickup,2,{rests:[{start:3,duration:1,sourceVoice:'1'}]});
assert.equal(pickupSplit.voices[0].find(n=>n.start===3)?.midi,72,'Upper-stem pickup stays in the upper line despite a sparse voice-number change');
assert.ok(!pickupSplit.voices[1].some(n=>n.start===3),'Written rest keeps the lower voice silent');
const staggered=[...notes,note(3,76,{stem:'up'}),note(4,74,{stem:'up'}),note(5,72,{stem:'up'}),note(5,60,{sourceVoice:'2',stem:'down'})];
const staggeredSplit=separateVoiceNotes(staggered,2,{rests:[{start:3,duration:2,sourceVoice:'2'}]});
assert.deepEqual(staggeredSplit.voices[0].filter(n=>n.start>=3).map(n=>n.midi),[76,74,72]);
assert.deepEqual(staggeredSplit.voices[1].filter(n=>n.start>=3).map(n=>n.midi),[60],'Lower written rest prevents false shared unison on a staggered entry');
const resumed=[...staggered,note(6,67)];
assert.ok(separateVoiceNotes(resumed,2,{rests:[{start:3,duration:2,sourceVoice:'2'}]}).voices.every(v=>v.at(-1).midi===67),'Shared unison resumes after explicit rests finish');
const chord=[72,67,64,60,55].map(midi=>note(0,midi));
const packed=separateVoiceNotes(chord,4,{unisons:false});
assert.equal(packed.voices.flat().length,5,'Too many chord tones are retained');assert.equal(packed.crowded,true);
const large=Array.from({length:1000},(_,i)=>[note(i,72+i%3),note(i,60+i%3)]).flat();
assert.equal(separateVoiceNotes(large,2).voices.flat().length,2000,'Long scores retain every note');
assert.throws(()=>separateVoiceNotes(notes,9),/two, three or four/);
console.log('Voice separation: continuity, crossings, ties, unisons, dense chords and long scores passed.');
